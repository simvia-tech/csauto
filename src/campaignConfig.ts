import * as fs from "fs";
import * as path from "path";

/** The csauto.toml keys the extension reads and edits; all top-level strings. */
export interface CampaignConfig {
  solver?: string;
  runtime?: string;
  docker_image?: string;
  saturne_bin?: string;
  singularity_image?: string;
}

const KEY_LINE = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"([^"]*)"/;
const TABLE_LINE = /^\s*\[/;

function configPath(root: string): string {
  return path.join(root, "csauto.toml");
}

/** Top-level string keys of a campaign's csauto.toml (the part before its first [table]). */
export function readCampaignConfig(root: string): CampaignConfig {
  const config: Record<string, string> = {};
  let text = "";
  try {
    text = fs.readFileSync(configPath(root), "utf-8");
  } catch {
    return config;
  }
  for (const line of text.split(/\r?\n/)) {
    if (TABLE_LINE.test(line)) {
      break;
    }
    const match = KEY_LINE.exec(line);
    if (match) {
      config[match[1]] = match[2];
    }
  }
  return config;
}

/** Set (or, with undefined, remove) top-level keys, leaving the rest of the file as written. */
export function writeCampaignConfig(root: string, changes: Partial<Record<keyof CampaignConfig, string | undefined>>): void {
  let lines: string[] = [];
  try {
    lines = fs.readFileSync(configPath(root), "utf-8").split(/\r?\n/);
  } catch {
    // A new file.
  }
  let topEnd = lines.findIndex((line) => TABLE_LINE.test(line));
  if (topEnd === -1) {
    topEnd = lines.length;
  }
  for (const [key, value] of Object.entries(changes)) {
    const index = lines.slice(0, topEnd).findIndex((line) => KEY_LINE.exec(line)?.[1] === key);
    if (value === undefined) {
      if (index !== -1) {
        lines.splice(index, 1);
        topEnd -= 1;
      }
    } else if (index !== -1) {
      lines[index] = `${key} = "${value}"`;
    } else {
      // After the last top-level key, so comments heading a [table] stay with it.
      let insertAt = 0;
      lines.slice(0, topEnd).forEach((line, lineIndex) => {
        if (/^\s*[A-Za-z_][A-Za-z0-9_]*\s*=/.test(line)) {
          insertAt = lineIndex + 1;
        }
      });
      lines.splice(insertAt, 0, `${key} = "${value}"`);
      topEnd += 1;
    }
  }
  const text = lines.join("\n");
  fs.writeFileSync(configPath(root), text.endsWith("\n") ? text : `${text}\n`, "utf-8");
}

/** The campaign's solver: the one `csauto prepare` recorded in RUNS/campaign.json, else csauto.toml's. */
export function campaignSolver(runsDir: string, root: string): string {
  try {
    const recorded = JSON.parse(fs.readFileSync(path.join(runsDir, "campaign.json"), "utf-8")) as { solver?: unknown };
    if (typeof recorded.solver === "string" && recorded.solver) {
      return recorded.solver;
    }
  } catch {
    // Not generated yet, or generated by an older csauto.
  }
  return readCampaignConfig(root).solver ?? "code_saturne";
}
