#!/usr/bin/env python3
"""Write csauto/solvers/telemac/keywords.py from the dictionaries of an openTELEMAC installation.

For each module, the keyword names (English NOM1 and French NOM) that no other
module's dictionary has: a steering file using them belongs to that module.

    python3 scripts/telemac_keywords.py "$HOMETEL" v9.1.0 > csauto/solvers/telemac/keywords.py

or, with the default docker image:

    docker run --rm -v "$PWD/scripts:/scripts:ro" simvia/opentelemac:v9.1.0 \
        python3 /scripts/telemac_keywords.py /opt/open_telemac v9.1.0 > csauto/solvers/telemac/keywords.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

# MASCARET steering files are a different format: it is not compared.
MODULES = ("telemac2d", "telemac3d", "tomawac", "artemis", "gaia", "waqtel", "khione", "stbtel", "postel3d")
NAME_PATTERN = re.compile(r"^NOM1?\s*=\s*'((?:[^']|'')*)'", re.M)


def keyword_names(dico: Path) -> set[str]:
    text = dico.read_text(encoding="latin-1")
    names = {" ".join(name.replace("''", "'").split()) for name in NAME_PATTERN.findall(text)}
    # Accented names depend on the steering file's encoding: keep the ASCII ones only.
    return {name for name in names if name and name.isascii()}


def main(hometel: str, version: str) -> None:
    sources = Path(hometel) / "sources"
    names = {module: keyword_names(sources / module / f"{module}.dico") for module in MODULES}
    print('"""Keywords found in one openTELEMAC module\'s dictionary only, English and French names.')
    print()
    print(f"Generated by scripts/telemac_keywords.py from the dictionaries of openTELEMAC {version}:")
    print("do not edit, run the script again for another version.")
    print('"""')
    print()
    print("UNIQUE_KEYWORDS: dict[str, frozenset[str]] = {")
    for module in MODULES:
        others = set().union(*(names[other] for other in MODULES if other != module))
        unique = sorted(names[module] - others)
        print(f"    {json.dumps(module)}: frozenset(")
        print("        {")
        for name in unique:
            print(f"            {json.dumps(name)},")
        print("        }")
        print("    ),")
    print("}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(f"usage: {sys.argv[0]} HOMETEL VERSION")
    main(sys.argv[1], sys.argv[2])
